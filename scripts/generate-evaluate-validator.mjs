/** Build-time only. Runtime imports no contract files, AJV or external validator helpers. */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standalone from "ajv/dist/standalone/index.js";
import ucs2module from "ajv/dist/runtime/ucs2length.js";

const directory = fileURLToPath(new URL("../contract/protocol/schemas/", import.meta.url));
const target = fileURLToPath(new URL("../core/protocol/generated/evaluate-validator.ts", import.meta.url));
const ajv = new Ajv2020({ strict: true, strictRequired: false, strictTypes: false, validateFormats: false, unicodeRegExp: false, inlineRefs: false, allErrors: false, code: { source: true, esm: true, lines: true } });
for (const [keyword, schemaType] of [["x-nmzp-halfOpen", "boolean"], ["x-nmzp-closure", "string"], ["x-nmzp-status", "string"]]) ajv.addKeyword({ keyword, schemaType });
for (const name of readdirSync(directory).filter(n => n.endsWith(".json")).sort()) ajv.addSchema(JSON.parse(readFileSync(`${directory}/${name}`, "utf8")));
const prefix = "https://nmzp.local/contract-candidate/";
let generated = standalone(ajv, { validateEvaluateCompat: `${prefix}canonical-evaluate-request-v2.schema.json`, validateEvaluateStrict: `${prefix}canonical-evaluate-request-v2-strict.schema.json`, validateEvaluateResponse: `${prefix}canonical-evaluate-response-v2.schema.json` });
const ucs2length = ucs2module.default ?? ucs2module;
generated = generated.replaceAll('require("ajv/dist/runtime/ucs2length").default', `(${ucs2length.toString()})`);
if (/\brequire\s*\(|\bimport\s/.test(generated)) throw new Error("Standalone validator contains a runtime dependency");
const output = `// @ts-nocheck\n// Generated by scripts/generate-evaluate-validator.mjs from the checked-in schemas.\n${generated}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) throw new Error("evaluate validator is out of date");
} else writeFileSync(target, output);
console.log(`evaluate-validator: ${process.argv.includes("--check") ? "exact" : "generated"}, self-contained`);
