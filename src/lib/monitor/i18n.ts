export type Msg = keyof typeof dict;

export function t(locale: Locale, key: Msg): string {
  const loc = locale === "en" ? "en" : "zh";
  const row = key ? dict[key] : undefined;
  if (!row) return typeof key === "string" ? key : "";
  return row[loc] ?? row.zh ?? "";
}

/** Event-derived home counts: pending until a successful CT sync. A real empty array is 0. */
export function homeReadyValue(dataReady: boolean, value: number, pending: string): number | string {
  return dataReady ? value : pending;
}

export function threatMsg(kind: ThreatKind): Msg {
  if (kind === "destructive") return "destructive";
  if (kind === "exfil") return "exfil";
  if (kind === "secret") return "secrets";
  if (kind === "tamper") return "tamper";
  if (kind === "isolate") return "isolate";
  if (kind === "poison") return "poison";
  return "high";
}

export function actorMsg(actor: "model" | "process" | "relay"): Msg {
  if (actor === "process") return "actorProcess";
  if (actor === "relay") return "actorRelay";
  return "actorModel";
}

/** Hook capability → honest label. Active needs a fresh host receipt; everything else is "configured, not verified". */
export function hookCapMsg(cap: { supported: boolean; active: boolean; error?: string } | undefined): Msg {
  if (!cap) return "hookCapNotReported";
  if (!cap.supported) return "hookCapNoAdapter";
  if (cap.active) return "hookCapActive";
  switch (cap.error) {
    case "hook_not_installed":
      return "hookCapNotInstalled";
    case "hook_untrusted":
      return "hookCapUntrusted";
    case "hook_modified":
      return "hookCapModified";
    case "hook_disabled":
      return "hookCapDisabled";
    case "hooks_feature_off":
      return "hookCapFeatureOff";
    case "offline":
    case undefined:
      return "hookCapNoReceipt";
    default:
      return "hookCapError";
  }
}

export function sourceMsg(source: string | undefined): Msg {
  if (source === "tool_command") return "sourceToolCommand";
  if (source === "tool_arg") return "sourceToolArg";
  if (source === "tool_path") return "sourceToolPath";
  if (source === "tool_url") return "sourceToolUrl";
  if (source === "tool_config") return "sourceToolConfig";
  if (source === "proc_cmdline") return "sourceProcCmdline";
  if (source === "probe_observation") return "sourceProbeObservation";
  return "sourceUnknown";
}
